// Builds games/fartnership/sim.js, the game's own simulation, from the
// Fartnership client bundle. The game runs the same world class (`hy` in the
// bundle) for local play and for the snapshots it expects from its server, so
// the server here steps that class instead of a rewrite of the physics.
//
//   node tools/fartnership-sim.mjs ../assets/misc/fartnership/assets/index-DSXVTYTO.js
//
// The bundle is one Vite module. This cuts the modulepreload polyfill at the
// top and the app boot at the end (`window.app=new class{…}(…)`, the only code
// that touches the DOM at load), exports the names the server uses, and lets
// esbuild drop everything they do not reach (renderer, UI, audio).
//
// The bundle's names are minified, so a new build of the game needs the
// EXPORTS below checked again: each is found from a string next to it.
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, "..", "games", "fartnership", "sim.js");
const ESBUILD = "esbuild@0.28.1";

const source = process.argv[2];
if (!source) {
  console.error("usage: node tools/fartnership-sim.mjs <path to the game's index-*.js>");
  process.exit(1);
}
let code = readFileSync(source, "utf8");

const boot = code.lastIndexOf("window.app=new class{");
if (boot < 0) throw new Error("app boot not found");
code = code.slice(0, boot);
const polyfillEnd = code.indexOf("})();");
if (!code.startsWith("(function(){let e=document.createElement(`link`)") || polyfillEnd < 0) {
  throw new Error("modulepreload polyfill not found");
}
code = code.slice(polyfillEnd + 5);

// Each export: [name here, regex whose group 1 is the bundle's name for it].
const EXPORTS = [
  ["World", /([\w$]+)=class\{course;setup;obstacles;rafts=\[\];/],
  [
    "loadCourse",
    /function ([\w$]+)\(e\)\{let t=[\w$]+\.get\(e\);if\(!t\)\{let n=[\w$]+\[e\];if\(!n\)throw Error\(`Unknown course/,
  ],
  ["raceCourses", /function ([\w$]+)\(\)\{return [\w$]+\(\)\.filter\(e=>!e\.arena\)\}/],
  ["MODES", /([\w$]+)=\{coop:\{name:`Co-op`/],
  ["isParty", /([\w$]+)=e=>[\w$]+\.includes\(e\),[\w$]+=\{move:0,fart:!1\}/],
  ["ANIMALS", /([\w$]+)=\[`hippo`,`capy`,`croc`,`pig`\]/],
  ["OUTFITS", /([\w$]+)=\[`none`,`briefs`,`kilt`,`diaper`,`tutu`\]/],
  ["STEP", /([\w$]+)=1\/60,[\w$]+=\{radius:/],
  ["EMOTES", /([\w$]+)=\[`Not me! 🙅`/],
];
const names = EXPORTS.map(([as, re]) => {
  const m = code.match(re);
  if (!m) throw new Error(`export ${as} not found`);
  return `${m[1]} as ${as}`;
});
code += `\nexport{${names.join(",")}};\n`;

const dir = mkdtempSync(path.join(tmpdir(), "fartnership-"));
try {
  const entry = path.join(dir, "entry.mjs");
  writeFileSync(entry, code);
  const built = execFileSync(
    "npx",
    [
      "--yes",
      ESBUILD,
      entry,
      "--bundle",
      "--format=esm",
      "--platform=neutral",
      "--tree-shaking=true",
      "--legal-comments=none",
    ],
    { maxBuffer: 64 * 1024 * 1024 },
  ).toString();
  const header =
    `// Generated by tools/fartnership-sim.mjs from Fartnership's ${path.basename(source)}.\n` +
    `// The game's own simulation; do not edit by hand.\n`;
  writeFileSync(OUT, header + built);
  console.log(`wrote ${OUT} (${Math.round(built.length / 1024)} KiB)`);
} finally {
  rmSync(dir, { recursive: true, force: true });
}
